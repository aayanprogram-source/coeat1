import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { startTestDatabase } from '../tests/harness';

const tsType: Record<string, string> = {
  uuid: 'string', text: 'string', citext: 'string', varchar: 'string', bpchar: 'string', timestamptz: 'string',
  timestamp: 'string', date: 'string', time: 'string', int2: 'number', int4: 'number', int8: 'number', numeric: 'number',
  float4: 'number', float8: 'number', bool: 'boolean', jsonb: 'Json', json: 'Json', void: 'void',
};

function map(udt: string): string {
  if (udt.startsWith('_')) return `${map(udt.slice(1))}[]`;
  return tsType[udt] ?? 'unknown';
}

const db = await startTestDatabase(54399);
try {
  const cols = await db.client.query<{ table_name: string; column_name: string; udt_name: string; is_nullable: string; has_default: boolean; is_view: boolean }>(
    `select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default is not null as has_default,
            t.table_type = 'VIEW' as is_view
     from information_schema.columns c join information_schema.tables t using (table_schema, table_name)
     where c.table_schema = 'public' and c.table_name <> 'schema_migrations'
     order by c.table_name, c.ordinal_position`,
  );
  const tables = new Map<string, typeof cols.rows>();
  for (const r of cols.rows) tables.set(r.table_name, [...(tables.get(r.table_name) ?? []), r]);

  const fns = await db.client.query<{ name: string; args: string[] | null; types: string[]; defaults: number; ret: string; setof: boolean }>(
    `select p.proname as name, p.proargnames as args,
            array(select t.typname from unnest(p.proargtypes::oid[]) with ordinality u(oid, n) join pg_type t on t.oid = u.oid order by u.n) as types,
            p.pronargdefaults as defaults, rt.typname as ret, p.proretset as setof
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
     where n.nspname = 'public' and p.prokind = 'f'
       and p.oid not in (select objid from pg_depend where deptype = 'e')
     order by p.proname`,
  );

  const lines: string[] = [
    '// Generated by pnpm db:types from the migrated schema. Do not edit by hand.',
    '',
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
    '',
    'export interface Database {',
    '  public: {',
    '    Tables: {',
  ];
  for (const [name, columns] of tables) {
    if (columns[0]?.is_view) continue;
    const row = columns.map((c) => `${c.column_name}: ${map(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('; ');
    lines.push(`      ${name}: { Row: { ${row} }; Insert: Record<string, unknown>; Update: Record<string, unknown>; Relationships: [] };`);
  }
  lines.push('    };', '    Views: {');
  for (const [name, columns] of tables) {
    if (!columns[0]?.is_view) continue;
    const row = columns.map((c) => `${c.column_name}: ${map(c.udt_name)} | null`).join('; ');
    lines.push(`      ${name}: { Row: { ${row} }; Relationships: [] };`);
  }
  lines.push('    };', '    Functions: {');
  const seen = new Set<string>();
  for (const f of fns.rows) {
    if (seen.has(f.name) || f.setof) continue;
    seen.add(f.name);
    const names = f.args ?? [];
    const firstOptional = names.length - f.defaults;
    const args = names.length === 0 ? 'Record<PropertyKey, never>' : `{ ${names.map((a, i) => `${a}${i >= firstOptional ? '?' : ''}: ${map(f.types[i] ?? 'unknown')}`).join('; ')} }`;
    lines.push(`      ${f.name}: { Args: ${args}; Returns: ${f.ret === 'void' ? 'undefined' : map(f.ret)} };`);
  }
  lines.push('    };', '  };', '}', '');
  writeFileSync(join(import.meta.dirname, '..', '..', 'core', 'src', 'database.types.ts'), lines.join('\n'));
  process.stdout.write(`Tables: ${tables.size}, functions: ${seen.size}\n`);
} finally {
  await db.stop();
}
