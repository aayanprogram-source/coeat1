import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { settingsRegistry } from '@datapal/core';
import { migrationsDir } from '../src/migrations';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const num = (n: number | undefined) => (n === undefined ? 'null' : String(n));

const rows = settingsRegistry.map((d) => {
  const value = JSON.stringify(d.initial);
  return `  (${q(d.key)}, ${q(value)}::jsonb, ${q(d.type)}, ${q(d.group)}, ${q(d.label)}, ${q(d.description)}, ${num(d.min)}, ${num(d.max)}, ${d.unit ? q(d.unit) : 'null'}, ${d.launchRequired ? 'true' : 'false'})`;
});

const sql = `-- Generated by pnpm db:settings from packages/core settings registry. Do not edit by hand.
-- These rows are structural configuration (keys, bounds and starting values), not sample data.
insert into platform_settings (key, value, type, "group", label, description, min, max, unit, launch_required) values
${rows.join(',\n')}
on conflict (key) do nothing;
`;

writeFileSync(join(migrationsDir, '0012_settings_defaults.sql'), sql);
